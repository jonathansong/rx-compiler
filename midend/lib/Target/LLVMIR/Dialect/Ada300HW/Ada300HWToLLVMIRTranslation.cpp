// Implements the LLVMTranslationDialectInterface for the Ada300HW dialect.
//
// Each Ada300HW op is translated directly to an LLVM IR intrinsic call
// (llvm.riscv.ada300_*).  The buddy RISC-V backend then emits the correct
// machine binary via the tablegen definitions in RISCVInstrInfoAda300HW.td.
//
// No intermediate lowering pass is required: Ada300HW ops already model
// ISA-level instructions, so we can map attributes and operands directly to
// LLVM IR constant/pointer values here.
//
// Operand conventions (matching IntrinsicsRISCVAda300HW.td):
//
//   Config ops   – attrs packed into two i64 LLVM IR constants.
//     set_gmm_cfg:  rs1 = row_size|(col_size<<8)|(acc_size<<16), rs2 = mode
//     set_gmm_type: rs1 = out_type|(act_type<<8),                rs2 = wht_type
//     set_gmm_iter: rs1 = blk_cnt_a,                             rs2 = blk_cnt_w
//
//   Execute ops  – aligned pointer extracted from LLVM memref descriptor.
//     {gmm,gmma,gmva,gmv}.*: rs1=dst ptr, rs2=act/mat ptr, rd=wht/vec ptr
//
//   Vector ops   – operand 0 is a vector value; attrs become i64 constants.
//     vfpwnl:     rs1=input, rs2=func enum, rs3=segments
//     vfcvt:      rs1=input, rs2=dst_type,  rs3=part
//     vfmul_{low,high}: rs1=lhs, rs2=rhs
//
//   Sync op      – no operands.
//     tcsync
//
//===----------------------------------------------------------------------===//

